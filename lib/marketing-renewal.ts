export function marketingContact(
  service: string,
  entry: string,
  plan = "",
  message = "",
) {
  const query = new URLSearchParams({ service, source: "marketing", entry });
  if (plan) query.set("plan", plan);
  if (message) query.set("message", message.slice(0, 400));
  return `/marketing/contact?${query}`;
}
